import { test, expect } from '@playwright/test';
import { user } from './helpers';
const folders = [{ id: 1, name: 'Hợp đồng' }, { id: 2, name: 'Báo cáo' }];
const docs = [{ id: 41, original_filename: 'contract.pdf', ai_label: 'Contract', folder_id: 1 }, { id: 42, original_filename: 'budget.docx', ai_label: 'Budget', folder_id: null }];
test('sidebar folder selection persists in the URL and browser history', async ({ page }) => {
  await page.request.post('/auth/login', { form: { username: user.email, password: user.password } });
  await page.route('**/api/folders?*', route => route.fulfill({ json: folders }));
  await page.route('**/api/documents?*', route => {
    const p = new URL(route.request().url()).searchParams;
    return route.fulfill({ json: docs.filter(doc => (!p.get('folder_id') || doc.folder_id === Number(p.get('folder_id'))) && (!p.get('unassigned') || doc.folder_id == null)) });
  });
  await page.goto('/workspace');
  const folder = page.getByRole('region', { name: 'Thư mục Hợp đồng', exact: true });
  const outside = page.getByRole('region', { name: 'Recents', exact: true });
  await expect(page.getByRole('button', { name: 'Mở thư mục Hợp đồng', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Mở thư mục Báo cáo', exact: true })).toBeVisible();
  await expect(outside.getByTestId('workspace-document-row')).toContainText('budget.docx');
  await expect(folder.getByTestId('workspace-document-row')).toHaveCount(0);
  await page.getByRole('button', { name: 'Mở thư mục Hợp đồng', exact: true }).click();
  await expect(page).toHaveURL('/workspace?folder=1');
  await expect(folder.getByTestId('workspace-document-row')).toHaveCount(1);
  await expect(outside.getByTestId('workspace-document-row')).toHaveCount(1);
  await page.reload();
  await expect(folder.getByTestId('workspace-document-row')).toContainText('contract.pdf');
  await expect(page.getByRole('status').filter({ hasText: 'Tài liệu mới sẽ được lưu' })).toContainText('Hợp đồng');
  await page.getByRole('button', { name: 'Ra ngoài thư mục' }).click();
  await expect(page.getByTestId('workspace-document-row')).toHaveCount(2);
  await page.goBack();
  await expect(folder.getByTestId('workspace-document-row')).toHaveCount(1);
});
